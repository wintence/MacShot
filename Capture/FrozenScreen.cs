using System.Windows.Media.Imaging;
using MacShot.Interop;

namespace MacShot.Capture;

/// <summary>
/// Замороженный кадр: снимок всего виртуального экрана на момент нажатия
/// горячей клавиши. Пока пользователь выбирает окно или растягивает область,
/// живой экран продолжает двигаться, а оверлей показывает этот кадр —
/// поэтому всё визуально «стоит на месте».
///
/// Окончательный снимок вырезается из кадра, а не с живого экрана: иначе
/// успевшее уехать содержимое не совпало бы с тем, что видел пользователь.
/// </summary>
internal readonly record struct FrozenScreen(WriteableBitmap Bitmap, Native.RECT Frame);
